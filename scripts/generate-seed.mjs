/**
 * Writes supabase/seed.sql from lib/content (for pasting into the SQL editor).
 *   node scripts/generate-seed.mjs
 * To seed directly instead: node --env-file=.env.local scripts/seed-db.mjs
 */
import { writeFileSync } from "node:fs";
import path from "node:path";

import { caseStudyRows, postRows, root, testimonialRows } from "./load-content.mjs";

// Dollar-quoting avoids every escaping problem with Markdown bodies.
const lit = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean" || typeof v === "number") return String(v);
  if (Array.isArray(v)) return `array[${v.map(lit).join(", ")}]::text[]`;
  const s = String(v);
  let tag = "$s$";
  for (let i = 0; s.includes(tag); i++) tag = `$s${i}$`;
  return `${tag}${s}${tag}`;
};

const insert = (table, rows, conflict) =>
  rows.map((row) => {
    const cols = Object.keys(row);
    const upsert = conflict
      ? `\non conflict (${conflict}) do update set ${cols.filter((c) => c !== conflict).map((c) => `${c} = excluded.${c}`).join(", ")}`
      : "";
    return `insert into public.${table} (${cols.join(", ")})\nvalues (${cols.map((c) => lit(row[c])).join(", ")})${upsert};\n`;
  });

const sql = [
  "-- Generated by scripts/generate-seed.mjs. Do not edit by hand. Re-runnable.",
  "",
  ...insert("case_studies", caseStudyRows, "slug"),
  ...insert("posts", postRows, "slug"),
  "-- Testimonials are PLACEHOLDERS, seeded unpublished. Replace with real ones, then publish.",
  "delete from public.testimonials;",
  ...insert("testimonials", testimonialRows),
].join("\n");

writeFileSync(path.join(root, "supabase/seed.sql"), sql);
console.log(`Wrote supabase/seed.sql: ${caseStudyRows.length} case studies, ${postRows.length} posts, ${testimonialRows.length} testimonials`);
